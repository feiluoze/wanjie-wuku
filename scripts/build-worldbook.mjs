// Offline build. Author text is data, never executable instructions.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { importBook } from '../src/core.js';
import { assert, clone, hash } from '../src/primitives.js';
import { BUILTIN_WORLDBOOK } from '../src/builtin-worldbook-data.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
assert(process.argv[2],'Usage: node scripts/build-worldbook.mjs latest.json [YYYY-MM-DD]');
const raw=await readFile(process.argv[2]),version=process.argv[3]||'2026-10-13';
assert(/^\d{4}-\d{2}-\d{2}$/.test(version),'规则日期格式无效');
const all=importBook(JSON.parse(raw.toString('utf8').replace(/^\uFEFF/,'')),'万界武库V4.1 · 内置');
// Historical duplicate only; uid72 now has its own name and must be retained.
const replacements={'升变之印':'122','旅法师':'119','一言为定':'123'};
const entries=all.filter(e=>!e.name.startsWith('太始天')||e.name.startsWith('太始天（完整版')).filter(e=>!replacements[e.name]||!all.some(n=>n.name===e.name&&n.entryId===replacements[e.name])||e.entryId===replacements[e.name]);
assert(new Set(entries.map(e=>e.name)).size===entries.length,'存在未审查的重复词条名称');
const data={...clone(BUILTIN_WORLDBOOK),version,sourceSha256:createHash('sha256').update(raw).digest('hex'),authorEntries:all.length,entries,sourceDuplicates:all.filter(e=>replacements[e.name]&&e.entryId!==replacements[e.name]&&entries.some(n=>n.name===e.name)).map(e=>({contentHash:hash(e.content),target:e.name}))};
delete data.overrides;
await writeFile(resolve(root,'data/builtin-worldbook.json'),JSON.stringify({name:'万界武库V4.1',entries:Object.fromEntries(entries.map(e=>[e.entryId,{uid:Number(e.entryId),comment:e.name,content:e.content,disable:!e.enabledInBook}]))},null,2)+'\n');
await writeFile(resolve(root,'src/builtin-worldbook-data.js'),'// Generated by scripts/build-worldbook.mjs. Author text is data, never executable code.\nexport const BUILTIN_WORLDBOOK = '+JSON.stringify(data)+';\n');
await writeFile(resolve(root,'data/taishi-rules.txt'),entries.find(e=>e.name.startsWith('太始天（完整版')).content);
console.log(JSON.stringify({authorEntries:all.length,builtinEntries:entries.length,sourceSha256:data.sourceSha256}));
